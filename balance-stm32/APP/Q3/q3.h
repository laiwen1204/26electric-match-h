#ifndef __Q3_H
#define __Q3_H

#include <stdint.h>

/* ============================================================================
 * 要求3: 小车静止, 钢球从摆杆中心 O 运行到 +5cm, 折返到 -5cm 并稳定
 * 指标: 总时间 <=5s, ±5cm 处最大误差绝对值 <=1cm
 * 视觉反馈 + 预测制动的分段状态机(加速/制动/捕获/保持),
 * 摄像头约 0.3s 延迟用超前预测补偿。
 * ============================================================================ */

void    q3_control_task(void);   /* 10ms 周期 */
uint8_t q3_start(void);          /* 启动滚球(与 q4 互斥), 1=成功 0=拒绝 */
void    q3_stop(void);           /* 停止并切断电机输出 */
uint8_t q3_is_idle(void);        /* 1=空闲(未运行) */
void    q3_print_status(void);   /* q3_status 命令: 打印状态机内部量 */

#endif /* __Q3_H */
